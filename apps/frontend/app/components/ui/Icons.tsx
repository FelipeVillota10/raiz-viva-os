export function getRoleIcon(nombre: string, className?: string, size?: number) {
  const icons: Record<string, React.FC<IconProps>> = {
    'productor': SeedIcon,
    'caminante': HikingIcon,
    'custodio': ShieldIcon,
    'facilitador': UsersIcon,
    'anfitrion': HomeIcon,
    'turista': CompassIcon,
  };

  const IconComponent = icons[nombre.toLowerCase()] || CompassIcon;
  return <IconComponent className={className} size={size || 24} />;
}